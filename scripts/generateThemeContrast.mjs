/**
 * Generates styles/themeContrast.css (master plan 3b.1). Edit THIS file and run
 *   node scripts/generateThemeContrast.mjs
 * - never the CSS by hand. It is a STOPGAP: the real fix is to migrate call sites to the `ink-*`
 * tokens and delete both files (Wave 1). scripts/ci/check-raw-muted-text-stops.ts stops it growing.
 *
 * In the LIGHT theme, dark-first text stops (`text-teal-400`, `text-slate-500`) are remapped to the
 * 800 weight of the same hue, which is AA on white, on #f3f4f6 and on the 20% tinted chips they sit on.
 * Text on a panel that is dark in BOTH themes keeps its palette colour: each remapped stop is a
 * custom property, light on <html>, and restored to the palette value on / inside a dark panel.
 */
import { createRequire } from 'node:module';
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const colors = createRequire(import.meta.url)('tailwindcss/colors');

const HUES_800 = ['teal', 'cyan', 'sky', 'blue', 'indigo', 'violet', 'purple', 'pink', 'rose', 'red', 'orange', 'amber', 'yellow', 'lime', 'green', 'emerald'];
const WITH_600 = new Set(['amber', 'yellow', 'orange', 'green', 'emerald', 'rose', 'lime']);
const NEUTRALS = ['slate', 'gray', 'zinc', 'neutral', 'stone'];
const NEUTRAL_LIGHT = '#5b6573';

/** A panel that stays dark in the light theme. Opaque dark utilities only: `bg-teal-900/30` is a tint. */
const DARK_PANELS = [
  '[data-surface="dark"]',
  '.bg-black',
  ...NEUTRALS.flatMap((h) => [700, 800, 900, 950].map((n) => `.bg-${h}-${n}`)),
  ...HUES_800.flatMap((h) => [800, 900, 950].map((n) => `.bg-${h}-${n}`)),
  ...NEUTRALS.flatMap((h) => [700, 800, 900, 950].map((n) => `.from-${h}-${n}`)),
  ...HUES_800.flatMap((h) => [800, 900, 950].map((n) => `.from-${h}-${n}`)),
  // arbitrary dark hex backgrounds (bg-[#1a1f2e]); the leading space keeps `dark:bg-[#1e293b]` out
  ...['0', '1', '2', '3'].flatMap((d) => [`[class^="bg-[#${d}"]`, `[class*=" bg-[#${d}"]`]),
];

/**
 * Where the 800 weights apply: the light theme, and a `data-surface="light"` panel inside the dark theme (white
 * there, so a raw text-slate-400 would sit at 2.6:1 on it).
 */
const LIGHT_SCOPES = [':where(html:not(.dark))', ':where(html.dark [data-surface="light"])'];

const stops = [];
for (const h of HUES_800) for (const n of [300, 400, 500, ...(WITH_600.has(h) ? [600] : [])]) stops.push([h, n, colors[h][800]]);
for (const h of NEUTRALS) for (const n of [400, 500]) stops.push([h, n, NEUTRAL_LIGHT]);

const v = (h, n) => `--tx-${h}-${n}`;
const lines = [];
lines.push(`/*
 * GENERATED by scripts/generateThemeContrast.mjs - do not edit by hand.
 * Theme contrast layer (master plan 3b.1), imported after globals.css. A STOPGAP: migrate call
 * sites to the ink-* tokens and delete this file (Wave 1). New raw text-gray/slate-400/500 stops
 * are refused by scripts/ci/check-raw-muted-text-stops.ts.
 *
 * The app grew dark-first: hundreds of files colour text with a light palette stop and no light twin.
 * In the LIGHT theme each such stop is remapped to the 800 weight of its hue. Text on or inside a
 * panel that is dark in both themes (bg-slate-700..950, bg-<hue>-800..950, from-*, bg-black, a dark
 * hex background, or data-surface="dark") keeps its palette colour.
 *
 * Every selector sits in :where(), so each rule is (0,1,0) like the utility it remaps; this file
 * loads after globals.css, and hover: / focus: / group-hover: / dark: variants still outrank it.
 */
`);
lines.push(`${LIGHT_SCOPES.join(',\n')} {`);
for (const [h, n, hex] of stops) lines.push(`  ${v(h, n)}: ${hex};`);
lines.push('}\n');
lines.push(`:where(${DARK_PANELS.join(', ')}),\n:where(${DARK_PANELS.join(', ')}) * {`);
for (const [h, n] of stops) lines.push(`  ${v(h, n)}: ${colors[h][n]};`);
lines.push('}\n');
for (const [h, n] of stops) {
  lines.push(`${LIGHT_SCOPES.map((sc) => `${sc} .text-${h}-${n}`).join(',\n')} {\n  color: var(${v(h, n)});\n}`);
}
lines.push(`
/*
 * Chart legends, BOTH themes (measured: rose-500 on the dark #1e293b card is 3.98:1 in dark, 1.8-3.5:1 on a
 * light card): recharts colours each label with its series (teal, orange, rose). The swatch beside the
 * label still carries the series colour.
 */
.recharts-legend-item-text {
  color: var(--ff-text-secondary) !important;
}
`);

// ── Titles on an always-dark banner ────────────────────────────────────────────────────────────────────────────
// ~20 pages draw their header on `bg-gradient-to-br from-slate-900 via-slate-800 to-slate-900` (dark in BOTH
// themes) and write the h1 as `text-slate-900 dark:text-white`: in the light theme that is near-black on
// near-black (1.0-1.2:1). Their back links (`text-slate-500 dark:text-slate-400`) read 3.1:1 and a few buttons
// (`text-gray-600`) 1.9:1. One rule here instead of ~20 page edits: on a dark gradient surface, in the light
// theme, slate/gray-900 text is white and the mid greys are the light grey the dark theme already uses.
// Specificity (0,1,0) like the utilities, so hover: / focus: variants still outrank it. The dark theme is not
// touched: its `dark:text-white` / `dark:text-slate-400` already win there.
const BANNER_SURFACES = [
  ...['slate', 'gray'].flatMap((h) => [800, 900, 950].map((n) => `.from-${h}-${n}`)),
  '.from-black',
];
const BANNER_LIGHT_PANEL_OPT_OUT = ':not(:where([data-surface="light"] *))';
const BANNER_ON_DARK_INK = '#ffffff';
const BANNER_ON_DARK_MUTED = '#a9b6c9'; // 8.7:1 on slate-900, 7.1:1 on slate-800 (the dark theme's tertiary text)
const bannerSelector = (cls) => `:where(html:not(.dark)) :where(${BANNER_SURFACES.join(', ')}) ${cls}${BANNER_LIGHT_PANEL_OPT_OUT}`;
lines.push(`
/*
 * Titles and muted text on an always-dark gradient banner (light theme only; see scripts/generateThemeContrast.mjs).
 * Put data-surface="light" on a light card nested inside a banner to opt it out.
 */`);
lines.push(`${['slate', 'gray'].map((h) => bannerSelector(`.text-${h}-900`)).join(',\n')} {\n  color: ${BANNER_ON_DARK_INK};\n}`);
lines.push(`${['slate', 'gray'].flatMap((h) => [500, 600, 700].map((n) => bannerSelector(`.text-${h}-${n}`))).join(',\n')} {\n  color: ${BANNER_ON_DARK_MUTED};\n}`);

/** The whole styles/themeContrast.css text. Exported so a test can hold the committed file to it. */
export const themeContrastCss = lines.join('\n');

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  writeFileSync(new URL('../styles/themeContrast.css', import.meta.url), themeContrastCss);
}
