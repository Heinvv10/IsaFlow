// Writes RESULTS.md (+ results.json in the scratch dir) for the entity-onboarding acceptance run.
// Only a FULL run writes the evidence RESULTS.md; a partial run (ONLY=...) writes RESULTS.partial.md to the scratch dir.
import { writeFileSync } from 'node:fs';
import { OUT, SCRATCH, type Result } from './entity-onboarding-support';
import { idFit, logoChecks, overflow } from './entity-onboarding-visual';

const fence = (lines: string[]) => ['```', ...lines, '```', ''];
const cell = (s: string) => s.replace(/\|/g, '\\|').replace(/\n/g, ' ');

export async function writeReport(results: Result[], full: boolean): Promise<void> {
  writeFileSync(`${SCRATCH}/results.json`, JSON.stringify(results, null, 2));
  const onb = results.filter(r => r.kind === 'onboarding');
  const server = results.filter(r => r.kind === 'server');
  const admin = results.filter(r => r.kind === 'admin');
  const lines: string[] = [
    '# Entity-first onboarding: browser acceptance, all 8 entity types', '',
    `Generated by \`scripts/acceptance/entity-onboarding.ts\` at ${new Date().toISOString()}${full ? '' : ' (PARTIAL run: ONLY=' + process.env.ONLY + ')'}. Synthetic data only; disposable Postgres.`, '',
    '## Per-type result', '',
    '| # | Entity code | Result | complete-setup HTTP (final) | Server refusals on the way (HTTP) | Screenshots |',
    '|---|---|---|---|---|---|',
    ...onb.map(r => `| ${r.n} | \`${r.entity}\` | ${r.status} | ${r.completeSetupStatus ?? 'none'} | ${(r.refusals ?? []).map(x => x.status).join(', ') || 'n/a'} | ${r.shots.length} |`),
    '',
  ];
  if (server.length) {
    lines.push('## Other scenarios', '', '| # | Scenario | Result |', '|---|---|---|', ...[...server, ...admin].map(r => `| ${r.n} | ${r.name} | ${r.status} |`), '');
  }
  for (const r of onb) {
    lines.push(`## ${r.n}. \`${r.entity}\` (${r.name}): ${r.status}`, '', '### Assertions and observations', '', ...fence(r.notes));
    if (r.refusals?.length) {
      lines.push('### Server refusals (POST /api/onboarding/complete-setup with the proof missing)', '', '| Case | HTTP | Message | Rows created |', '|---|---|---|---|',
        ...r.refusals.map(x => `| ${cell(x.label)} | ${x.status} | ${cell(x.message)} | ${x.created} |`), '');
    }
    if (r.dbEvidence) lines.push('### Database rows for the NEW company (disposable DB, verbatim psql)', '', ...fence(r.dbEvidence.flatMap(b => [b, ''])));
    lines.push('### Screenshots', '', ...r.shots.map(s => `- \`${s}\``), '');
  }
  for (const r of server) {
    lines.push(`## ${r.n}. ${r.name}: ${r.status}`, '');
    if (r.refusals?.length) {
      lines.push('| Case | HTTP | Message | Rows created (companies, company_directors, company_documents, company_users) |', '|---|---|---|---|',
        ...r.refusals.map(x => `| ${cell(x.label)} | ${x.status} | ${cell(x.message)} | ${x.created} |`), '');
    }
    lines.push('### Assertions', '', ...fence(r.notes));
    if (r.dbEvidence?.length) lines.push('### Database rows for the accepted requests (verbatim psql)', '', ...fence(r.dbEvidence.flatMap(b => [b, ''])));
  }
  if (admin.length) {
    lines.push('## Admin company-link scenarios', '', '| # | Scenario | Result |', '|---|---|---|', ...admin.map(r => `| ${r.n} | ${r.name} | ${r.status} |`), '');
    for (const r of admin) lines.push(`### ${r.n}. ${r.name}`, '', ...fence(r.notes), ...r.shots.map(s => `- \`${s}\``), '');
  }
  lines.push('## Measurements (each is also an assertion in the scenario notes above)', '', '### Horizontal overflow at 390px', '', ...fence(overflow),
    '### ID inputs at 390px', '', ...fence(idFit), '### Light-mode logo and cards (entity step)', '', ...fence(logoChecks));
  writeFileSync(full ? `${OUT}/RESULTS.md` : `${SCRATCH}/RESULTS.partial.md`, lines.join('\n'));
}
