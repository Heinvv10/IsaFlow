// Writes RESULTS.md (+ results.json in the scratch dir) for the entity-onboarding acceptance run.
import { writeFileSync } from 'node:fs';
import { OUT, SCRATCH, idFit, logoChecks, overflow, type Result } from './entity-onboarding-support';

export async function writeReport(results: Result[]): Promise<void> {
  writeFileSync(`${SCRATCH}/results.json`, JSON.stringify(results, null, 2));
  const onb = results.filter(r => r.entity);
  const admin = results.filter(r => !r.entity);
  const refusalCell = (r: Result) => (r.refusals ?? []).map(x => `${x.status}`).join(', ') || 'n/a';
  const lines: string[] = [
    '# Entity-first onboarding: browser acceptance, all 8 entity types', '',
    `Generated by \`scripts/acceptance/entity-onboarding.ts\` at ${new Date().toISOString()}. Synthetic data only; disposable Postgres.`, '',
    '## Per-type result', '',
    '| # | Entity code | Result | complete-setup HTTP (final) | Server refusals when proof missing (HTTP) | Screenshots |',
    '|---|---|---|---|---|---|',
    ...onb.map(r => `| ${r.n} | \`${r.entity}\` | ${r.status} | ${r.completeSetupStatus ?? 'none'} | ${refusalCell(r)} | ${r.shots.length} |`),
    '',
  ];
  for (const r of onb) {
    lines.push(`## ${r.n}. \`${r.entity}\` (${r.name}): ${r.status}`, '', '### Assertions and observations', '', '```', ...r.notes, '```', '');
    if (r.refusals?.length) {
      lines.push('### Server refusals (POST /api/onboarding/complete-setup with the proof missing)', '', '```');
      for (const x of r.refusals) lines.push(`${x.label}: HTTP ${x.status} ${x.body}`);
      lines.push('```', '');
    }
    if (r.dbEvidence) lines.push('### Database rows for the NEW company (disposable DB, verbatim psql)', '', '```', ...r.dbEvidence.flatMap(b => [b, '']), '```', '');
    lines.push('### Screenshots', '', ...r.shots.map(s => `- \`${s}\``), '');
  }
  if (admin.length) {
    lines.push('## Admin company-link scenarios', '', '| # | Scenario | Result |', '|---|---|---|', ...admin.map(r => `| ${r.n} | ${r.name} | ${r.status} |`), '');
    for (const r of admin) lines.push(`### ${r.n}. ${r.name}`, '', '```', ...r.notes, '```', '', ...r.shots.map(s => `- \`${s}\``), '');
  }
  lines.push('## Measurements', '', '### Horizontal overflow at 390px', '', '```', ...overflow, '```', '', '### ID inputs at 390px', '', '```', ...idFit, '```', '',
    '### Light-mode logo and cards (entity step)', '', '```', ...logoChecks, '```', '');
  writeFileSync(`${OUT}/RESULTS.md`, lines.join('\n'));
}
