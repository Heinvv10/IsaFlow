#!/usr/bin/env node

import { readdir, readFile, stat, writeFile } from 'node:fs/promises';
import path from 'node:path';

const excludedDirectories = new Set([
  '.claude',
  '.git',
  '.next',
  '.worktrees',
  'coverage',
  'node_modules',
  'worktrees',
]);

function toPosixPath(filePath) {
  return filePath.split(path.sep).join('/');
}

function renderMirror(sourcePath, canonicalLabel, content) {
  const sourceName = path.basename(sourcePath);
  return `<!-- Auto-generated by scripts/mirror-agent-docs.mjs from ${sourceName}. Do not edit manually. -->\n` +
    `<!-- Canonical source: ${canonicalLabel} -->\n\n` +
    content;
}

/** Dirent type for a symlink is neither file nor directory, so a symlinked
 *  `.claude.md` (or a symlinked directory containing one) would be skipped
 *  silently and never drift-checked. Resolve those through stat(). */
async function resolveEntryKind(entry, entryPath) {
  if (entry.isDirectory()) return 'directory';
  if (entry.isFile()) return 'file';
  if (!entry.isSymbolicLink()) return 'other';

  try {
    const target = await stat(entryPath);
    if (target.isDirectory()) return 'directory';
    if (target.isFile()) return 'file';
  } catch {
    return 'other'; // broken symlink — nothing to mirror
  }
  return 'other';
}

async function findNestedSources(rootDirectory, directory = rootDirectory, sources = []) {
  const entries = await readdir(directory, { withFileTypes: true });

  for (const entry of entries) {
    const entryPath = path.join(directory, entry.name);
    const kind = await resolveEntryKind(entry, entryPath);

    if (kind === 'directory') {
      if (!excludedDirectories.has(entry.name)) {
        await findNestedSources(rootDirectory, entryPath, sources);
      }
      continue;
    }

    if (kind === 'file' && entry.name === '.claude.md') {
      sources.push(entryPath);
    }
  }

  return sources;
}

async function findMirrorDefinitions(rootDirectory) {
  const definitions = [];
  const rootSource = path.join(rootDirectory, 'CLAUDE.md');

  try {
    const content = await readFile(rootSource, 'utf8');
    definitions.push({
      sourcePath: rootSource,
      mirrorPath: path.join(rootDirectory, 'AGENTS.md'),
      sourceLabel: 'CLAUDE.md',
      mirrorLabel: 'AGENTS.md',
      content,
    });
  } catch (error) {
    if (error?.code !== 'ENOENT') {
      throw error;
    }
  }

  const nestedSources = await findNestedSources(rootDirectory);
  for (const sourcePath of nestedSources.sort()) {
    const directory = path.dirname(sourcePath);
    const relativeDirectory = path.relative(rootDirectory, directory);
    const mirrorLabel = toPosixPath(path.join(relativeDirectory, 'AGENTS.md'));
    definitions.push({
      sourcePath,
      mirrorPath: path.join(directory, 'AGENTS.md'),
      sourceLabel: './.claude.md',
      mirrorLabel,
      content: await readFile(sourcePath, 'utf8'),
    });
  }

  // Two sources claiming one mirror can never both be satisfied: generate
  // would last-write-wins and check would report a permanent, unfixable STALE.
  // The live case is a root `.claude.md` sitting beside `CLAUDE.md` — both
  // target ./AGENTS.md. Fail loudly instead of oscillating.
  const seen = new Map();
  for (const definition of definitions) {
    const claimed = seen.get(definition.mirrorPath);
    if (claimed) {
      throw new Error(
        `Two canonical sources target the same mirror ${definition.mirrorLabel}: ` +
          `${toPosixPath(path.relative(rootDirectory, claimed))} and ` +
          `${toPosixPath(path.relative(rootDirectory, definition.sourcePath))}. ` +
          'Remove one — a mirror can only have a single source.',
      );
    }
    seen.set(definition.mirrorPath, definition.sourcePath);
  }

  return definitions;
}

async function inspectMirrors(rootDirectory) {
  const definitions = await findMirrorDefinitions(rootDirectory);
  const results = [];

  for (const definition of definitions) {
    const expected = renderMirror(definition.sourcePath, definition.sourceLabel, definition.content);
    try {
      const actual = await readFile(definition.mirrorPath, 'utf8');
      results.push({ ...definition, expected, status: actual === expected ? 'OK' : 'STALE' });
    } catch (error) {
      if (error?.code === 'ENOENT') {
        results.push({ ...definition, expected, status: 'MISSING' });
      } else {
        throw error;
      }
    }
  }

  return results;
}

async function generateMirrors(rootDirectory) {
  const definitions = await findMirrorDefinitions(rootDirectory);

  for (const definition of definitions) {
    await writeFile(
      definition.mirrorPath,
      renderMirror(definition.sourcePath, definition.sourceLabel, definition.content),
    );
    console.log(`GENERATED: ${definition.mirrorLabel}`);
  }

  console.log(`Generated ${definitions.length} agent document mirror(s).`);
}

async function checkMirrors(rootDirectory) {
  const results = await inspectMirrors(rootDirectory);
  const failures = results.filter((result) => result.status !== 'OK');

  for (const result of failures) {
    console.log(`${result.status}: ${result.mirrorLabel} (source: ${result.sourceLabel})`);
  }

  if (failures.length > 0) {
    console.log(`Agent document check failed: ${failures.length} mirror(s) need regeneration.`);
    return 1;
  }

  console.log(`OK: ${results.length} agent document mirror(s) match canonical sources.`);
  return 0;
}

async function main() {
  const arguments_ = process.argv.slice(2);
  if (arguments_.some((argument) => argument !== '--check')) {
    console.error('Usage: node scripts/mirror-agent-docs.mjs [--check]');
    return 2;
  }

  const rootDirectory = process.cwd();
  if (arguments_.includes('--check')) {
    return checkMirrors(rootDirectory);
  }

  await generateMirrors(rootDirectory);
  return 0;
}

main()
  .then((exitCode) => {
    process.exitCode = exitCode;
  })
  .catch((error) => {
    console.error(error instanceof Error ? error.stack : String(error));
    process.exitCode = 1;
  });
