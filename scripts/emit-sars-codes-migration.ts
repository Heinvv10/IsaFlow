/**
 * Emit migration 999m (the 2024 and 2025 SARS source-code sets) from the committed workbooks.
 *
 *   bun scripts/emit-sars-codes-migration.ts          # rewrite scripts/migrations/sql/999m_*.sql
 *   bun scripts/emit-sars-codes-migration.ts --check  # exit 1 when the committed file differs
 *
 * Rows come through the same parser and category/status maps as scripts/import-sars-codes.ts and the admin upload
 * (src/modules/admin/services/sarsCodesParser.ts). The upsert has the importer's ON CONFLICT (code, effective_year)
 * shape, but only rewrites a row whose content differs, so a second run is a true no-op (imported_at stays).
 * It never touches sars_code_releases.is_current: the current year stays whatever it is.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { parseSarsCodesXlsxFile, type ParsedSarsRow } from '../src/modules/admin/services/sarsCodesParser';

export const SARS_MIGRATION_FILE = 'scripts/migrations/sql/999m_sars_source_codes_2024_2025.sql';
export const SARS_MIGRATION_SOURCES = [
  { year: 2024, brs: 'v22.1.2', file: 'scripts/data/sars-codes/IRP5-CODES-FULL-LIST-2024-from-BRS.xlsx' },
  { year: 2025, brs: 'v23.0.0', file: 'scripts/data/sars-codes/IRP5-CODES-FULL-LIST-2025-from-BRS.xlsx' },
] as const;

const COLS = ['code', 'effective_year', 'category', 'description', 'status', 'foreign_code', 'code_pair',
  'applicability_note', 'rationalisation_note', 'source_document', 'source_url', 'official_excerpt', 'brs_version'];
const UPDATED = COLS.filter((c) => c !== 'code' && c !== 'effective_year');

function lit(v: string | null): string {
  if (v === null) return 'NULL';
  if (v.includes('\0')) throw new Error('NUL byte in a SARS code cell');
  return `'${v.replace(/'/g, "''")}'`;
}

function valuesRow(r: ParsedSarsRow, year: number, brs: string): string {
  return `  (${[r.code, String(year), r.category, r.description, r.status, r.foreignCode, r.codePair,
    r.applicabilityNote, r.rationalisationNote, r.sourceDocument, r.sourceUrl, r.officialExcerpt, brs]
    .map((v, i) => (i === 1 ? String(year) : lit(v))).join(', ')})`;
}

function yearBlock(rows: ParsedSarsRow[], year: number, brs: string): string {
  const sorted = [...rows].sort((a, b) => a.code.localeCompare(b.code));
  const set = UPDATED.map((c) => `${c} = EXCLUDED.${c}`).join(',\n  ');
  const cmp = (p: string) => `(${UPDATED.map((c) => `${p}${c}`).join(', ')})`;
  return `-- ${year}: ${sorted.length} codes, BRS ${brs}
INSERT INTO sars_source_codes (${COLS.join(', ')}) VALUES
${sorted.map((r) => valuesRow(r, year, brs)).join(',\n')}
ON CONFLICT (code, effective_year) DO UPDATE SET
  ${set},
  imported_at = now()
WHERE ${cmp('sars_source_codes.')} IS DISTINCT FROM ${cmp('EXCLUDED.')};
`;
}

export async function buildSarsCodesMigration(root: string): Promise<string> {
  const blocks: string[] = [];
  for (const s of SARS_MIGRATION_SOURCES) {
    const { rows, errors } = await parseSarsCodesXlsxFile(resolve(root, s.file));
    if (errors.length) throw new Error(`${s.file}: ${errors.join('; ')}`);
    blocks.push(yearBlock(rows, s.year, s.brs));
  }
  const releases = SARS_MIGRATION_SOURCES.map((s) => `(${s.year}, '${s.brs}', now(), false)`).join(', ');
  return `-- Migration 999m: SARS IRP5/IT3(a) source codes for the 2024 and 2025 years of assessment.
--
-- Production still held the 19-row legacy seed for both years (wrong meanings for 4003-4005, no 4006, no 3696-3699),
-- so IRP5_UNKNOWN_CODE fired on real codes. These are the full sets from the SARS PAYE Employer Reconciliation BRS
-- (section 6.5-6.7), built into the two workbooks under scripts/data/sars-codes/. isaflow_app has no access to these
-- tables, so the deploy role applies them. GENERATED by scripts/emit-sars-codes-migration.ts; do not edit by hand
-- (tests/unit/scripts/sarsCodesMigration.test.ts regenerates it and diffs).
--
-- Idempotent: a row is rewritten only when its content differs, so a second run changes nothing. Data only, no DDL,
-- no DELETE: the old colour keeps working while it runs. sars_code_releases.is_current is never touched.
-- Rollback: the previous rows cannot be restored from the app role; they were the legacy seed (19 rows per year).

${blocks.join('\n')}
INSERT INTO sars_code_releases (effective_year, brs_version, released_at, is_current) VALUES ${releases}
ON CONFLICT (effective_year) DO UPDATE SET brs_version = EXCLUDED.brs_version
WHERE sars_code_releases.brs_version IS DISTINCT FROM EXCLUDED.brs_version;
`;
}

if (import.meta.main) {
  const root = resolve(import.meta.dir, '..');
  const sql = await buildSarsCodesMigration(root);
  const target = resolve(root, SARS_MIGRATION_FILE);
  if (process.argv.includes('--check')) {
    const same = readFileSync(target, 'utf8') === sql;
    console.log(same ? 'up to date' : `${SARS_MIGRATION_FILE} differs from the workbooks`);
    process.exit(same ? 0 : 1);
  }
  writeFileSync(target, sql);
  console.log(`wrote ${SARS_MIGRATION_FILE}`);
}
