/**
 * THE COMMENTARY GATE'S WIDTHS ARE AN UPPER BOUND ON PAGE 4'S (Hein, 11-10: the editor's `commentaryCost` uses the
 * page's widths, without the font ruler in the browser). `packProseAdvanceData.PROSE_ADVANCES` is, for every code point
 * the faces set, its advance in the regular face (or what the ruler sets it alone at, where it sets it as another) plus
 * the most any kerning pair adds where it is the glyph the face adjusts, in font units, read here from `public/fonts` by fontkit (every code point laid out beside every other). It
 * fails on drift from the faces; REGENERATE_PROSE_ADVANCES=1 writes the table afresh. A word's bound is then never under
 * the width the ruler shapes it at (`packProseBound.boundPx` against `packFigureWidth.textExactPx`, held below).
 */
import { writeFileSync } from 'node:fs';
import path from 'node:path';
import { describe, expect, it } from 'vitest';
import { PROSE_ADVANCES, PROSE_ADVANCE_UNITS } from '@/modules/accounting/services/packs/pages/packProseAdvanceData';
import { EXACT_RANGES, FALLBACK, SELF_HOSTED } from '@/modules/accounting/services/packs/pages/packFallbackWidthData';
import { PROSE_FACES, PROSE_FALLBACK, PROSE_FALLBACK_RANGES } from '@/modules/accounting/services/packs/pages/packProseFallbackData';
import { boundPx, FALLBACK_MARK, proseLinesBound } from '@/modules/accounting/services/packs/pages/packProseBound';
import { proseLines } from '@/modules/accounting/services/packs/pages/packProseLines';
import { PROSE } from '@/modules/accounting/services/packs/pages/packProseStyles';
import { textExactPx } from '@/modules/accounting/services/packs/pages/packFigureWidth';
import { fontsDir, inFace, loadFace } from '@/modules/accounting/services/packs/pages/packGlyphRuler';
import { punctuationTexts } from '../../print/fixtures/proseLinkTexts';

const ROOT = path.resolve(__dirname, '../../../..');
const codePoints = (): number[] => SELF_HOSTED.flatMap(([from, to]) => Array.from({ length: to - from + 1 }, (unused, i) => from + i));

/** Each code point's advance plus its largest positive kerning adjustment, in font units, in `SELF_HOSTED` order. */
function measured(): { units: number; values: number[] } {
  const face = loadFace(fontsDir(), 400);
  const cps = codePoints();
  const kern = new Map<number, number>();
  for (const a of cps) {
    // `a` beside every code point the faces set, either side: each glyph's adjustment is what the pair adds to it.
    const run = face.layout(cps.map((b) => String.fromCodePoint(a) + String.fromCodePoint(b)).join(''));
    run.glyphs.forEach((glyph, i) => {
      const added = run.positions[i]!.xAdvance - glyph.advanceWidth;
      for (const cp of glyph.codePoints) if (added > (kern.get(cp) ?? 0)) kern.set(cp, added);
    });
  }
  // The ruler sets a few code points as another (a line or paragraph separator as a space: `packGlyphShaping.asShaped`):
  // each is charged at least what the ruler sets it alone at, in font units.
  const alone = (cp: number): number => Math.ceil((textExactPx(String.fromCodePoint(cp), 100, 400) * face.unitsPerEm) / 100 - 1e-9);
  // A code point the ruler does not set in the face (`inFace`: U+FFFF) is priced from the fallback tables, as the
  // ruler prices it: marked FALLBACK_MARK.
  return { units: face.unitsPerEm, values: cps.map((cp) => (inFace(String.fromCodePoint(cp)) ? Math.max(face.glyphForCodePoint(cp).advanceWidth, alone(cp)) + (kern.get(cp) ?? 0) : FALLBACK_MARK)) };
}

function source({ units, values }: { units: number; values: number[] }): string {
  const encoded = values.map((v) => v.toString(36).padStart(3, '0')).join('');
  const lines = Array.from({ length: Math.ceil(encoded.length / 105) }, (unused, i) => `  '${encoded.slice(i * 105, i * 105 + 105)}'`).join(' +\n');
  return `/**
 * GENERATED by tests/unit/services/packs/packProseAdvances.test.ts from public/fonts: do not edit by hand.
 * Regenerate: REGENERATE_PROSE_ADVANCES=1 npx vitest run tests/unit/services/packs/packProseAdvances.test.ts
 *
 * For each code point IBM Plex Sans sets (\`packFallbackWidthData.SELF_HOSTED\`, in its order), its advance in the regular
 * face plus the largest positive kerning adjustment it takes beside any other, in font units, three base-36 digits each:
 * an upper bound on its width in any word (\`packProseBound\`); "zzz" where the ruler does not set it in the face (it is
 * priced from the fallback tables). Client-safe data.
 */
export const PROSE_ADVANCE_UNITS = ${units};

export const PROSE_ADVANCES =
${lines};
`;
}

/** The gate's own copy of what it reads of the fallback tables: the faces' code points and the regular label style. */
function fallbackSource(): string {
  const ranges = (list: ReadonlyArray<readonly [number, number]>): string => `[${list.map(([a, b]) => `[0x${a.toString(16)}, 0x${b.toString(16)}]`).join(', ')}]`;
  const t = FALLBACK.label400;
  const chunks = (text: string): string => Array.from({ length: Math.ceil(text.length / 105) }, (unused, i) => `    '${text.slice(i * 105, i * 105 + 105)}'`).join(' +\n');
  return `/**
 * GENERATED by tests/unit/services/packs/packProseAdvances.test.ts from packFallbackWidthData: do not edit by hand.
 * Regenerate: REGENERATE_PROSE_ADVANCES=1 npx vitest run tests/unit/services/packs/packProseAdvances.test.ts
 *
 * What the commentary gate (\`packProseBound\`) reads of the fallback tables, and no more, so the editor does not load
 * every style's (#1263 L2): the code points the faces set, the per-glyph ranges, and the regular label style's table.
 * Client-safe data.
 */
import type { FallbackTable } from './packFallbackWidthData';

export const PROSE_FACES: ReadonlyArray<readonly [number, number]> = ${ranges(SELF_HOSTED)};

export const PROSE_FALLBACK_RANGES: ReadonlyArray<readonly [number, number]> = ${ranges(EXACT_RANGES)};

export const PROSE_FALLBACK: FallbackTable = {
  exact:
${chunks(t.exact)},
  blocks:
${chunks(t.blocks)},
  wide: { ${Object.entries(t.wide).map(([k, v]) => `0x${Number(k).toString(16)}: ${v}`).join(', ')} },
  widest: ${t.widest},
  emoji: ${t.emoji},
  fingerprint: [${t.fingerprint.join(', ')}],
};
`;
}

describe('the commentary gate\'s fallback table', () => {
  it('is the regular label style\'s, and the faces\' code points, as packFallbackWidthData holds them', () => {
    if (process.env.REGENERATE_PROSE_ADVANCES === '1') writeFileSync(path.join(ROOT, 'src/modules/accounting/services/packs/pages/packProseFallbackData.ts'), fallbackSource());
    expect(PROSE_FACES).toEqual(SELF_HOSTED);
    expect(PROSE_FALLBACK_RANGES).toEqual(EXACT_RANGES);
    expect(PROSE_FALLBACK).toEqual(FALLBACK.label400);
  });
});

describe('the commentary gate\'s advance table', () => {
  it('is the faces\' advances and kerning, read afresh', () => {
    const now = measured();
    if (process.env.REGENERATE_PROSE_ADVANCES === '1') writeFileSync(path.join(ROOT, 'src/modules/accounting/services/packs/pages/packProseAdvanceData.ts'), source(now));
    expect(PROSE_ADVANCE_UNITS).toBe(now.units);
    expect(PROSE_ADVANCES.length).toBe(now.values.length * 3);
    const drift = now.values.flatMap((v, i) => (parseInt(PROSE_ADVANCES.slice(i * 3, i * 3 + 3), 36) === v ? [] : [codePoints()[i]!.toString(16)]));
    expect(drift.slice(0, 10)).toEqual([]);
  }, 120_000);

  it('bounds every word at or over the width the ruler shapes it at: every pair and run of the faces\' code points', () => {
    const cps = codePoints().map((cp) => String.fromCodePoint(cp));
    const words = [
      ...cps.flatMap((a) => cps.filter((unused, j) => j % 7 === 0).map((b) => a + b)),
      'Revenue', 'Telecommunications', 'AVAWAYATAVATWAYAV', 'r’r’r’', 'fïfi', 'LTYPVAWA%@&#', 'JE-2026-00417', '1 234 567.89',
    ];
    const under = words.filter((w) => boundPx(w, 13.333) < textExactPx(w, 13.333, 400) - 1e-9);
    expect(under.slice(0, 10)).toEqual([]);
  }, 120_000);

  it('so the gate never reads page 4\'s commentary in fewer lines than the page model does', () => {
    const texts = [
      'Revenue grew on the Gauteng rollout. Costs were held flat while the depot in Pretoria opened.',
      'AVAWAYATAVATWAYAV '.repeat(40), '%%%% @@@@ &&&& '.repeat(30), 'a'.repeat(46).concat(' ').repeat(20),
      'Journal JE-2026-00061 (recorded well after its entry date): payroll run 2026-01. '.repeat(10),
      `Rent${'　'.repeat(16)}March `.repeat(10), '株式会社テストへの支払い '.repeat(20),
    ];
    for (const t of texts) for (const mm of [174, 110, 60]) expect(proseLinesBound(t, PROSE.narrativeBody, mm), `${t.slice(0, 20)} at ${mm}mm`).toBeGreaterThanOrEqual(proseLines(t, PROSE.narrativeBody, mm));
  });

  it('nor on clusters past the unshaped length, repeated marks or a mark on a foreign base (#1263 round 3)', () => {
    const texts = [`${'\u1780'}${'\u17B6'.repeat(32)} `.repeat(20), `${'\u1780'}${'\u17B6'.repeat(31)} `.repeat(20), `${'\u1780'}${'\u17B6'.repeat(3)}`.repeat(200),
      'm\u102C'.repeat(300), '\u1040\u102D'.repeat(300), '\u0E81\u0ECE'.repeat(300), `e${'\u0301'.repeat(40)} `.repeat(30)];
    for (const t of texts) for (const mm of [174, 110, 60, 24.4]) {
      expect(proseLinesBound(t, PROSE.narrativeBody, mm), `${JSON.stringify(t.slice(0, 6))} at ${mm}mm`).toBeGreaterThanOrEqual(proseLines(t, PROSE.narrativeBody, mm));
    }
  });

  it('and both remember a width at its own size: the same text costs more lines set larger, whichever is asked first', () => {
    // The ruler's and the bound's widths are kept across calls (`packProseLines`, `packProseBound`), keyed by size.
    const t = 'Revenue grew on the Gauteng rollout while costs were held flat at the Pretoria depot. '.repeat(6);
    for (const lines of [proseLines, proseLinesBound]) {
      const large = lines(t, PROSE.narrativeBody, 110);
      const small = lines(t, PROSE.footnote, 110);
      expect(small, lines.name).toBeLessThan(large);
      expect(lines(t, PROSE.narrativeBody, 110), lines.name).toBe(large);
    }
  });

  it('nor where a line ends at a soft hyphen, which sets a hyphen there: every half millimetre from 20 to 120', () => {
    // The hyphen is a few pixels: a line one hyphen from full is found only by sweeping the measure.
    const texts = [...punctuationTexts().filter((t) => t.includes('\u00AD')), 'Rev\u00ADenue grew on the Gau\u00ADteng roll\u00ADout'.repeat(4)];
    const short: string[] = [];
    for (const t of texts) {
      for (let mm = 20; mm <= 120; mm += 0.5) {
        if (proseLinesBound(t, PROSE.narrativeBody, mm) < proseLines(t, PROSE.narrativeBody, mm)) short.push(`${t.slice(0, 20)} at ${mm}mm`);
      }
    }
    expect(short.slice(0, 10)).toEqual([]);
  }, 120_000);
});
