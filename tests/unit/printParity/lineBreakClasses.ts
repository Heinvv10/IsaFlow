/**
 * UNICODE'S LINE-BREAK CLASSES AS SOURCE: Unicode's `LineBreak.txt` (17.0, the version this was generated from) read
 * into a class per code point, and written as the two tables that read them:
 *  - `packNumericClassData.ts`: the classes Unicode's numeric rule (UAX 14 LB25) reads, for `packNumericHold.ts`;
 *  - `tests/unit/print/fixtures/lineBreakLetterData.ts`: the letters a word-opening hyphen holds to (AL and HL), for
 *    the census's reading of the print tests' Chromium (`fixtures/breakPairsCensus.asProduction`).
 *  - `tests/unit/print/fixtures/emojiVariationBases.ts`: the bases of emoji-variation-sequences.txt (17.0, in
 *    https://www.unicode.org/Public/17.0.0/ucd/emoji/), for the VS16 census's expected printed text.
 * LineBreak.txt is https://www.unicode.org/Public/17.0.0/ucd/LineBreak.txt. The letters are regenerated by
 * `lineBreakClasses.test.ts` with LINE_BREAK_TXT set to its path; the numeric classes, which production's Chromium is
 * probed for (`numericProbes`), by `packNumericHoldImage.test.ts` with REGENERATE_NUMERIC=1 and LINE_BREAK_TXT.
 */

/** Each code point `LineBreak.txt` lists, with its class (the rest are XX). */
export function parseLineBreak(text: string): Map<number, string> {
  const out = new Map<number, string>();
  for (const raw of text.split('\n')) {
    const line = raw.split('#')[0]!.trim();
    if (line === '') continue;
    const [range, cls] = line.split(';').map((s) => s.trim());
    const [from, to] = range!.split('..');
    for (let c = parseInt(from!, 16); c <= parseInt(to ?? from!, 16); c += 1) out.set(c, cls!);
  }
  return out;
}

/** The runs of consecutive code points whose class is one of `wanted`: [first, last, index in `wanted`]. */
export function classRuns(classes: ReadonlyMap<number, string>, wanted: readonly string[]): Array<[number, number, number]> {
  const out: Array<[number, number, number]> = [];
  for (const [code, cls] of [...classes].sort((a, b) => a[0] - b[0])) {
    const k = wanted.indexOf(cls);
    if (k < 0) continue;
    const last = out[out.length - 1];
    if (last !== undefined && last[1] === code - 1 && last[2] === k) last[1] = code; else out.push([code, code, k]);
  }
  return out;
}

const runLines = (runs: ReadonlyArray<readonly [number, number, number]>): string => Array.from({ length: Math.ceil(runs.length / 8) }, (unused, i) => `  ${runs.slice(i * 8, i * 8 + 8).map(([a, b, c]) => `[0x${a.toString(16)}, 0x${b.toString(16)}, ${c}]`).join(', ')},`).join('\n');

/** `source` with every character past ASCII written as an escape (a generated file is ASCII). */
export const ascii = (source: string): string => source.replace(/[^\x00-\x7F]/g, (c) => `\\u${c.charCodeAt(0).toString(16).toUpperCase().padStart(4, '0')}`);

/** The classes `packNumericHold.ts` reads, in its order. */
export const NUMERIC_CLASSES = ['NU', 'SY', 'IS', 'CL', 'CP', 'PO', 'PR', 'OP', 'HY'] as const;

/**
 * A probe of production's Chromium: does it hold the break at `at` in `text`, where the numeric rule would hold it for
 * `code` in its class? A code point the rule's class names but production does not hold beside is left out of the table.
 */
export interface NumericProbe { text: string; at: number; code: number }

/** The probes for each code point of `domain` the numeric rule names (Latin-1 signs excepted, below). */
export function numericProbes(classes: ReadonlyMap<number, string>, domain: readonly number[]): NumericProbe[] {
  const out: NumericProbe[] = [];
  const add = (code: number, texts: ReadonlyArray<readonly [string, number]>): void => { for (const [text, at] of texts) out.push({ text, at, code }); };
  for (const code of domain) {
    const x = String.fromCodePoint(code);
    const cls = classes.get(code);
    // A Latin-1 sign meets a Latin-1 neighbour by Chromium's own table, pair by pair, which the pair table already holds.
    if ((cls === 'PO' || cls === 'PR') && code >= 0x100) {
      add(code, [[`ab1.)${x}c`, 5], [`ab1/:${x}`, 5], [`ab1,${x}c`, 4], [`ab1..${x}`, 5], [`ab${x}(.5`, 3], [`ab${x}[,5`, 3], [`ab${x}-.5`, 3]]);
    } else if (cls === 'OP' || cls === 'HY') {
      add(code, [[`ab\u20AC${x}.5`, 3], [`ab\u2212${x},5`, 3]]);
    } else if (cls === 'IS' || cls === 'SY') {
      add(code, [...(cls === 'IS' ? [[`ab\u20AC(${x}5`, 3] as const] : []), [`ab1${x}\u2033`, 4], [`ab1${x}.\u2033`, 5]]);
    } else if (cls === 'CL' || cls === 'CP') {
      add(code, [[`ab1.${x}\u2033`, 5], [`ab1/${x}\u20AC`, 5]]);
    } else if (cls === 'NU') {
      add(code, [[`ab${x}.)\u2033`, 5], [`ab\u20AC(.${x}`, 3]]);
    }
  }
  return out;
}

/** The code points production does not hold beside in every probe: `breaks[i]`, production's breaks in `probes[i]`. */
export function notInNumbers(probes: readonly NumericProbe[], breaks: readonly number[][]): Set<number> {
  const out = new Set<number>();
  probes.forEach((p, i) => { if (breaks[i]!.includes(p.at)) out.add(p.code); });
  return out;
}

export function numericClassSource(classes: ReadonlyMap<number, string>, left: ReadonlySet<number> = new Set()): string {
  const runs = classRuns(new Map([...classes].filter(([code]) => !left.has(code))), NUMERIC_CLASSES);
  const leftOut = [...left].sort((a, b) => a - b).map((c) => `U+${c.toString(16).toUpperCase().padStart(4, '0')}`).join(' ');
  return `/**
 * GENERATED from Unicode 17.0's LineBreak.txt and production's image by \`tests/unit/printParity/packNumericHoldImage.test.ts\`
 * (REGENERATE_NUMERIC=1 LINE_BREAK_TXT=...): do not edit by hand. The code points of the classes Unicode's numeric rule reads (UAX 14 LB25), for
 * \`packNumericHold.ts\`: [first, last, class], the class an index into ${NUMERIC_CLASSES.join(', ')}. ${runs.length} runs.
 * Left out, as production's Chromium holds no number beside them (probed in its image): ${leftOut || 'none'}.
 */
export const NUMERIC_CLASS_RANGES: ReadonlyArray<readonly [number, number, number]> = [
${runLines(runs)}
];
`;
}

export function letterSource(classes: ReadonlyMap<number, string>): string {
  const runs = classRuns(classes, ['AL', 'HL']);
  return `/**
 * GENERATED from Unicode 17.0's LineBreak.txt by \`tests/unit/printParity/lineBreakClasses.test.ts\` (LINE_BREAK_TXT=...):
 * do not edit by hand. The code points of line-break class AL (0) and HL (1), the letters a word-opening hyphen holds to
 * in production's Chromium (\`breakPairsCensus.asProduction\`). ${runs.length} runs.
 */
export const LETTER_RANGES: ReadonlyArray<readonly [number, number, number]> = [
${runLines(runs)}
];
`;
}

/** The code points emoji-variation-sequences.txt gives an emoji style (a U+FE0F sequence) to. */
export function variationBases(text: string): number[] {
  return [...new Set([...text.matchAll(/^([0-9A-F]+) FE0F/gm)].map((m) => parseInt(m[1]!, 16)))].sort((a, b) => a - b);
}

export function variationBaseSource(bases: readonly number[]): string {
  const lines = Array.from({ length: Math.ceil(bases.length / 12) }, (unused, i) => `  ${bases.slice(i * 12, i * 12 + 12).map((c) => `0x${c.toString(16)}`).join(', ')},`);
  return `/**
 * GENERATED from Unicode 17.0's emoji-variation-sequences.txt by \`tests/unit/printParity/lineBreakClasses.test.ts\`
 * (EMOJI_VARIATION_TXT=...): do not edit by hand. The ${bases.length} code points with an emoji style (a U+FE0F sequence): the
 * census's own reading of where the pack keeps a U+FE0F, apart from \`packPrintedText.ts\`'s.
 */
export const EMOJI_VARIATION_BASES: readonly number[] = [
${lines.join('\n')}
];
`;
}

/**
 * A Latin-1 pair with a mark on its first character (\`packMarkedLatin1.ts\`), as production's Chromium breaks it: `codes`
 * the Latin-1 characters the pair table covers, `breaks[a * codes.length + b]` whether it breaks between codes[a] with a
 * mark and codes[b], a letter either side ("a" + x + U+0301 + y + "a", probed in the image); `opening` the same with
 * nothing before (x + U+0301 + y + "a"); `hyphenAfter` an unmarked hyphen after a marked character (c + U+0301 + "-" + y).
 */
export function markedLatin1Source(
  codes: readonly number[], breaks: readonly boolean[], opening: readonly boolean[], hyphenAfter: readonly boolean[], opensAfter: readonly number[], holdsAfter: readonly number[],
): string {
  const lines = (bits: readonly boolean[]): string => {
    const bytes = new Uint8Array(Math.ceil(bits.length / 8));
    bits.forEach((b, i) => { if (b) bytes[i >> 3] = bytes[i >> 3]! | (1 << (7 - (i & 7))); });
    const b64 = Buffer.from(bytes).toString('base64');
    return Array.from({ length: Math.ceil(b64.length / 160) }, (unused, i) => `  '${b64.slice(i * 160, (i + 1) * 160)}',`).join('\n');
  };
  const codeLines = Array.from({ length: Math.ceil(codes.length / 16) }, (unused, i) => `  ${codes.slice(i * 16, i * 16 + 16).map((c) => `0x${c.toString(16)}`).join(', ')},`);
  return ascii(`/**
 * GENERATED in production's image by \`tests/unit/printParity/packMarkedLatin1Image.test.ts\` (REGENERATE_MARKED=1): do not
 * edit by hand. Read by \`packMarkedLatin1.ts\`: whether production's Chromium breaks between a Latin-1 character with a
 * mark on it and the Latin-1 character after it, a letter either side. ${codes.length} characters, ${breaks.filter(Boolean).length} breaks.
 */
export const MARKED_LATIN1_CODES: readonly number[] = [
${codeLines.join('\n')}
];

/** Bits by first x ${codes.length} + second (the first the high bit), base64: after a letter. */
export const MARKED_LATIN1_BREAKS = [
${lines(breaks)}
].join('');

/** The same where the first character opens a word (nothing before it). */
export const MARKED_LATIN1_OPENING = [
${lines(opening)}
].join('');

/** A hyphen after codes[c] with a mark: whether it breaks before codes[y], by c x ${codes.length} + y ("?\u0301-\u00B2" breaks). */
export const MARKED_LATIN1_HYPHEN_AFTER = [
${lines(hyphenAfter)}
].join('');

/** Before a marked hyphen, one of each pair class that breaks it as \`MARKED_LATIN1_OPENING\` does (a no-break space, ...). */
export const MARKED_HYPHEN_OPENS_AFTER: readonly number[] = [${opensAfter.map((c) => `0x${c.toString(16)}`).join(', ')}];

/** Before a marked hyphen, one of each pair class after which it never breaks (a Hebrew letter). */
export const MARKED_HYPHEN_HOLDS_AFTER: readonly number[] = [${holdsAfter.map((c) => `0x${c.toString(16)}`).join(', ')}];
`);
}
