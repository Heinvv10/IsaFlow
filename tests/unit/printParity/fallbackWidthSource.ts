/**
 * The source of `packFallbackWidthData.ts`, from the image's measurements (`fallbackWidths.ts`) and the self-hosted
 * faces' coverage.
 */
import { readFileSync } from 'node:fs';
import path from 'node:path';
import * as fontkit from 'fontkit';
import { FINGERPRINT_CLUSTERS, FIRST, LAST, STYLES, type FallbackStyle } from './fallbackWidths';

export const EXACT_RANGES: ReadonlyArray<readonly [number, number]> = [[0x20, 0x2bff], [0x1d400, 0x1d7ff]];
const MAX_DIGIT = 35;
const LINE = 400;

const chunks = (digits: string): string => {
  const rows: string[] = [];
  for (let i = 0; i < digits.length; i += LINE) rows.push(`    '${digits.slice(i, i + LINE)}'`);
  return rows.join(' +\n');
};

/** The code points the self-hosted faces have glyphs for, as ranges. */
export function selfHostedRanges(): Array<[number, number]> {
  const cps = new Set<number>();
  for (const file of ['IBMPlexSans-Regular.woff2', 'IBMPlexSans-Medium.woff2', 'IBMPlexSans-SemiBold.woff2']) {
    for (const cp of fontkit.create(readFileSync(path.join(process.cwd(), 'public/fonts', file))).characterSet) cps.add(cp);
  }
  const sorted = [...cps].filter((cp) => cp >= 0x20).sort((a, b) => a - b);
  const ranges: Array<[number, number]> = [];
  for (const cp of sorted) {
    const last = ranges[ranges.length - 1];
    if (last !== undefined && last[1] === cp - 1) last[1] = cp; else ranges.push([cp, cp]);
  }
  return ranges;
}

export function fallbackWidthSource(
  advances: Record<FallbackStyle, number[]>, emoji: Record<FallbackStyle, number>, fingerprint: Record<FallbackStyle, number[]>, image: string,
): string {
  const at = (style: FallbackStyle, cp: number): number => advances[style][cp - FIRST]!;
  const tables = STYLES.map(([style]) => {
    const wide: string[] = [];
    let exact = '';
    for (const [from, to] of EXACT_RANGES) for (let cp = from; cp <= to; cp += 1) {
      const px = at(style, cp);
      if (px > MAX_DIGIT) wide.push(`0x${cp.toString(16)}: ${px}`);
      exact += Math.min(px, MAX_DIGIT).toString(36);
    }
    let blocks = '';
    const widestBlock: number[] = [];
    for (let base = 0; base <= LAST; base += 32) {
      let widest = 0;
      for (let cp = Math.max(base, FIRST); cp < base + 32 && cp <= LAST; cp += 1) if (cp < 0xd800 || cp > 0xf8ff) widest = Math.max(widest, at(style, cp));
      widestBlock.push(widest);
      if (widest > MAX_DIGIT) wide.push(`0x${base.toString(16)}: ${widest}`);
      blocks += Math.min(widest, MAX_DIGIT).toString(36);
    }
    return `  ${style}: {
    exact:
${chunks(exact)},
    blocks:
${chunks(blocks)},
    wide: { ${wide.join(', ')} },
    widest: ${Math.max(...widestBlock)},
    emoji: ${emoji[style]},
    fingerprint: [${fingerprint[style].join(', ')}],
  },`;
  });
  const covered = selfHostedRanges().map(([a, b]) => `[0x${a.toString(16)}, 0x${b.toString(16)}]`);
  return `/**
 * GENERATED by tests/unit/printParity/fallbackWidthSource.ts from measurements in ${image}: do not edit by hand.
 * Regenerate (velo): REGENERATE_FALLBACK_WIDTHS=1 npx vitest run --config vitest.print.config.ts tests/unit/printParity/packFallbackWidths.test.ts
 *
 * What a glyph the pack's self-hosted faces lack costs on production's render host, per style (\`packFallbackWidth.ts\`
 * reads it): the advance of each code point of ${EXACT_RANGES.map(([a, b]) => `U+${a.toString(16).toUpperCase()}-U+${b.toString(16).toUpperCase()}`).join(' and ')} in whole
 * pixels rounded up (base 36, capped at 35; \`wide\` holds the rest), the widest advance of every block of 32 code
 * points to U+${LAST.toString(16).toUpperCase()} (\`blocks\`), the widest of all (\`widest\`, for anything beyond), the widest emoji
 * presentation, and the fingerprint: the exact width, in 1/64px, of each of FINGERPRINT_CLUSTERS.
 */
export type FallbackStyle = ${STYLES.map(([s]) => `'${s}'`).join(' | ')};

export interface FallbackTable { exact: string; blocks: string; wide: Readonly<Record<number, number>>; widest: number; emoji: number; fingerprint: readonly number[] }

export const EXACT_RANGES: ReadonlyArray<readonly [number, number]> = [${EXACT_RANGES.map(([a, b]) => `[0x${a.toString(16)}, 0x${b.toString(16)}]`).join(', ')}];

export const FINGERPRINT_CLUSTERS: readonly string[] = ${JSON.stringify(FINGERPRINT_CLUSTERS).replace(/[\u007f-￿]/g, (c) => `\\u${c.charCodeAt(0).toString(16).padStart(4, '0')}`)};

/** The code points the self-hosted faces (IBM Plex Sans 400, 500, 600) have glyphs for. */
export const SELF_HOSTED: ReadonlyArray<readonly [number, number]> = [${covered.join(', ')}];

export const FALLBACK: Readonly<Record<FallbackStyle, FallbackTable>> = {
${tables.join('\n')}
};
`;
}
