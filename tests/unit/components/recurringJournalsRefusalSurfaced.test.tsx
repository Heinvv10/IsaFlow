/**
 * K-048 round 2, MEDIUM 1 — the refusals the route sends must reach the person.
 *
 * `doAction` awaited `apiFetch` and threw the response away. `apiFetch` RESOLVES
 * on 4xx (it only intercepts 401 to refresh), so every message the generate
 * guards produce — not due until <date>, no fiscal period, closed period, a
 * deactivated account named by its code, an unbalanced template — and the 409
 * for a contended generate were discarded, the list reloaded unchanged, and the
 * button looked dead. The route tests all assert on `statusCode` and body, which
 * is exactly why none of them caught it.
 *
 * Rendered, not grepped: the defect is a missing branch in an event handler.
 */
import { describe, it, expect, vi, beforeEach, afterEach } from 'vitest';
import React from 'react';
import { fireEvent, render, screen, waitFor } from '@testing-library/react';

vi.mock('next/router', () => ({
  useRouter: () => ({ pathname: '/accounting/recurring-journals', isReady: true, query: {}, push: vi.fn(), events: { on: () => {}, off: () => {} } }),
}));
vi.mock('@/components/layout/AppLayout', () => ({
  AppLayout: ({ children }: { children: React.ReactNode }) => React.createElement('div', null, children),
}));

const TEMPLATE = {
  id: '11111111-1111-4111-8111-111111111111',
  templateName: 'Monthly rent accrual',
  frequency: 'monthly',
  nextRunDate: '2027-06-01',
  runCount: 0,
  status: 'active',
  totalAmount: 1000,
  lines: [],
};

const ok = (data: unknown) => new Response(JSON.stringify({ success: true, data }), {
  status: 200, headers: { 'Content-Type': 'application/json' },
});

/** The route's own refusal envelope, as `apiResponse.badRequest` sends it. */
const refusal = (status: number, message: string) => new Response(
  JSON.stringify({ success: false, message }),
  { status, headers: { 'Content-Type': 'application/json' } },
);

let actionResponse: Response;
const fetchMock = vi.fn(async (url: string) => {
  if (String(url).includes('recurring-journals-action')) return actionResponse.clone();
  if (String(url).includes('recurring-journals')) return ok({ items: [TEMPLATE] });
  return ok({ accounts: [] });
});

async function mountPage() {
  const { default: Page } = await import('../../../pages/accounting/recurring-journals/index');
  render(React.createElement(Page));
  await screen.findByText('Monthly rent accrual');
}

describe('recurring journals page — a refused generate is shown, not swallowed', () => {
  beforeEach(() => {
    fetchMock.mockClear();
    vi.stubGlobal('fetch', fetchMock);
  });
  afterEach(() => { vi.unstubAllGlobals(); });

  it('shows the route\'s 400 message when the run is not due', async () => {
    actionResponse = refusal(400, 'Recurring journal is not due until 2027-06-01. Change the next run date to generate it earlier.');
    await mountPage();

    fireEvent.click(screen.getByTitle('Generate Now'));

    await waitFor(() => expect(screen.getByText(/not due until 2027-06-01/)).toBeInTheDocument());
  });

  it('shows the deactivated account the route named', async () => {
    actionResponse = refusal(400, 'This recurring journal template posts to deactivated GL account: 2000 Accruals. Reactivate the account, or recode the template.');
    await mountPage();

    fireEvent.click(screen.getByTitle('Generate Now'));

    await waitFor(() => expect(screen.getByText(/2000 Accruals/)).toBeInTheDocument());
  });

  it('shows the 409 for a contended generate', async () => {
    actionResponse = refusal(409, 'Recurring journal is being generated by another request — retry in a moment.');
    await mountPage();

    fireEvent.click(screen.getByTitle('Generate Now'));

    await waitFor(() => expect(screen.getByText(/retry in a moment/)).toBeInTheDocument());
  });

  it('falls back to its own wording when the refusal carries no message', async () => {
    actionResponse = new Response('', { status: 500 });
    await mountPage();

    fireEvent.click(screen.getByTitle('Generate Now'));

    await waitFor(() => expect(screen.getByText(/Could not generate this recurring journal/)).toBeInTheDocument());
  });

  it('re-enables the button after a refusal, and reloads the list after a success', async () => {
    actionResponse = refusal(400, 'Recurring journal is not due until 2027-06-01.');
    await mountPage();

    const button = screen.getByTitle('Generate Now');
    fireEvent.click(button);
    await waitFor(() => expect(screen.getByText(/not due until/)).toBeInTheDocument());
    // `busy` cleared in a finally, so a second attempt is possible at all.
    expect(button).not.toBeDisabled();

    actionResponse = ok({ journalId: 'je-1' });
    const before = fetchMock.mock.calls.length;
    fireEvent.click(button);
    await waitFor(() => expect(screen.queryByText(/not due until/)).not.toBeInTheDocument());
    expect(fetchMock.mock.calls.length).toBeGreaterThan(before + 1);
  });
});
