/**
 * THE GENERATOR OF `packReasonWidthData.ts`: every glyph's advance in `.pack-kpi-unavailable`, measured in Chromium.
 *
 * Each code point from U+0020 to U+1FFFF is set between two bars in the class itself, under the real print
 * stylesheet with its faces loaded (`openProbePage`), and its advance is the width less the two bars', rounded UP to a
 * whole pixel. One layout per batch of 8192. From those advances:
 *  - `LATIN` holds U+0020 to U+017F, one number each;
 *  - `EXACT` holds U+0180 to U+04FF, U+1E00 to U+2BFF and U+1D400 to U+1D7FF, one base-36 digit each (35 at most);
 *  - the `BLOCKS_*` strings hold every other block of 32 code points up to U+1FFFF as the WIDEST advance in it, one
 *    base-36 digit each; a block wider than 35 is in `WIDE_BLOCKS` and its digit is `z`. Surrogates and the private use
 *    area (U+E000 to U+F8FF) are 0: `reasonPx` charges a 0 that is not a mark the widest glyph.
 * Run `REGENERATE_REASON_WIDTHS=1 npx vitest run --config vitest.print.config.ts tests/unit/print/packReasonWidthData.generate.test.ts`.
 */
import type { Browser } from 'playwright';
import { openProbePage } from './measureWidths';

export const FIRST = 0x20;
export const LAST = 0x1ffff;
const BATCH = 8192;
const BLOCK = 32;
const MAX_DIGIT = 35;

/** The advance of every code point from `FIRST` to `LAST`, in whole pixels rounded up; index = code point - FIRST. */
export async function measureReasonAdvances(browser: Browser): Promise<number[]> {
  const page = await openProbePage(browser);
  try {
    return await page.evaluate(({ first, last, batch }) => {
      const td = document.getElementById('label')!;
      const probe = (text: string): HTMLSpanElement => {
        const line = document.createElement('div');
        const span = document.createElement('span');
        span.className = 'pack-kpi-unavailable';
        span.textContent = text;
        line.appendChild(span);
        td.appendChild(line);
        return span;
      };
      td.textContent = '';
      const bars = probe('||').getBoundingClientRect().width;
      td.textContent = '';
      const out: number[] = [];
      for (let from = first; from <= last; from += batch) {
        const spans: HTMLSpanElement[] = [];
        for (let cp = from; cp < Math.min(from + batch, last + 1); cp += 1) {
          spans.push(probe(cp >= 0xd800 && cp <= 0xdfff ? '||' : `|${String.fromCodePoint(cp)}|`));
        }
        for (const span of spans) out.push(Math.max(0, Math.ceil(span.getBoundingClientRect().width - bars - 0.001)));
        td.textContent = '';
      }
      return out;
    }, { first: FIRST, last: LAST, batch: BATCH });
  } finally {
    await page.close();
  }
}

export interface ReasonWidthData {
  latin: number[];
  exact: string;
  blocksLow: string;
  blocksBmpHigh: string;
  blocksAstral: string;
  wideBlocks: Record<number, number>;
}

const isUncharted = (cp: number): boolean => (cp >= 0xd800 && cp <= 0xf8ff);

export function reasonWidthData(advances: readonly number[]): ReasonWidthData {
  const at = (cp: number): number => advances[cp - FIRST]!;
  const range = (from: number, to: number): number[] => Array.from({ length: to - from + 1 }, (unused, i) => from + i);
  const wideBlocks: Record<number, number> = {};
  const blocks = (from: number, to: number): string => {
    let digits = '';
    for (let base = from; base <= to; base += BLOCK) {
      const widest = Math.max(0, ...range(base, base + BLOCK - 1).map((cp) => (isUncharted(cp) ? 0 : at(cp))));
      if (widest > MAX_DIGIT) wideBlocks[base] = widest;
      digits += widest > MAX_DIGIT ? 'z' : widest.toString(36);
    }
    return digits;
  };
  const exact = [...range(0x180, 0x4ff), ...range(0x1e00, 0x2bff), ...range(0x1d400, 0x1d7ff)]
    .map((cp) => Math.min(MAX_DIGIT, at(cp)).toString(36)).join('');
  return {
    latin: range(0x20, 0x17f).map((cp) => (cp >= 0x7f && cp <= 0x9f ? 0 : at(cp))),
    exact,
    blocksLow: blocks(0x500, 0x1dff),
    blocksBmpHigh: blocks(0x2c00, 0xffff),
    blocksAstral: blocks(0x10000, 0x1ffff),
    wideBlocks,
  };
}

const lines = (digits: string): string => {
  const rows: string[] = [];
  for (let i = 0; i < digits.length; i += 100) rows.push(`  '${digits.slice(i, i + 100)}'`);
  return rows.join(' +\n');
};

/** The source of `packReasonWidthData.ts`. */
export function dataModuleSource(data: ReasonWidthData, measuredIn: string): string {
  const latin: string[] = [];
  for (let i = 0; i < data.latin.length; i += 16) latin.push(`  ${data.latin.slice(i, i + 16).join(', ')},`);
  const wide = Object.entries(data.wideBlocks).map(([base, px]) => `  0x${Number(base).toString(16)}: ${px},`);
  return `/**
 * GENERATED by tests/unit/print/reasonWidthGenerator.ts: do not edit by hand. Measured in ${measuredIn}.
 * Regenerate: REGENERATE_REASON_WIDTHS=1 npx vitest run --config vitest.print.config.ts tests/unit/print/packReasonWidthData.generate.test.ts
 *
 * The advance of each glyph in \`.pack-kpi-unavailable\` (11pt italic), in whole pixels rounded up. Read by
 * \`packReasonWidth.ts\`, which says what each table covers.
 */

/** U+0020 to U+017F, one number each (U+007F to U+009F are controls: 0). */
export const LATIN: readonly number[] = [
${latin.join('\n')}
];

/** U+0180 to U+04FF, U+1E00 to U+2BFF, U+1D400 to U+1D7FF: one base-36 digit each, 35 at most. */
export const EXACT =
${lines(data.exact)};

/** U+0500 to U+1DFF: the widest advance in each block of 32, one base-36 digit each. */
export const BLOCKS_LOW =
${lines(data.blocksLow)};

/** U+2C00 to U+FFFF: the widest advance in each block of 32 (surrogates and private use: 0). */
export const BLOCKS_BMP_HIGH =
${lines(data.blocksBmpHigh)};

/** U+10000 to U+1FFFF: the widest advance in each block of 32. */
export const BLOCKS_ASTRAL =
${lines(data.blocksAstral)};

/** Blocks wider than a base-36 digit holds, by the block's first code point (their digit is \`z\`). */
export const WIDE_BLOCKS: Readonly<Record<number, number>> = {
${wide.join('\n')}
};
`;
}
