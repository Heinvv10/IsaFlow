/**
 * The shared UUID schema must accept every id Postgres does.
 *
 * The bug: Zod 4's `z.string().uuid()` enforces the RFC 4122 version and
 * variant nibbles. `00000000-0000-0000-0000-000000000001` — the ISAFlow Demo
 * company — has neither, so it was REJECTED, and every endpoint validating a
 * company_id with the shared `UUID` returned 400 for that tenant. Eight
 * endpoints in production, two of them tenant-facing (company-logo, AFS
 * management-pack-config). Zod 3's `.uuid()` accepted it, so this arrived
 * silently with the Zod 4 upgrade rather than with any code change.
 *
 * The principle, and why the fix is `z.guid()` rather than special-casing the
 * demo id: Postgres's `uuid` type stores any 128-bit value and cares nothing
 * for version bits. An API that validates more strictly than its own database
 * can reject a row that legitimately exists — which is exactly what happened.
 * `z.guid()` checks the 8-4-4-4-12 hex shape, which is precisely what Postgres
 * accepts, and still rejects malformed input.
 *
 * Verified against production before the fix: of 911 ids sampled across
 * companies, plans, users, gl_accounts and subscriptions, exactly ONE failed
 * the strict check — the demo company — and `z.guid()` rejects none of them.
 */
import { describe, it, expect } from 'vitest';
import { UUID } from '@/lib/schemas/common';

/** The ISAFlow Demo company. Seeded, not generated by gen_random_uuid(). */
const DEMO_COMPANY_ID = '00000000-0000-0000-0000-000000000001';

describe('UUID — accepts what the database accepts', () => {
  it('accepts the seeded demo company id', () => {
    // The regression this file exists for.
    expect(UUID.safeParse(DEMO_COMPANY_ID).success).toBe(true);
  });

  it('accepts a normal gen_random_uuid() value', () => {
    expect(UUID.safeParse('ec278d98-8726-4ee2-ad32-2db940c9c0fe').success).toBe(true);
  });

  it('accepts other shapes Postgres would store', () => {
    // Any 128-bit value is a valid `uuid` to Postgres.
    //
    // Note these three passed the STRICT check too, which is what makes the
    // demo id such an easy trap: Zod 4 blesses the nil and max UUIDs as RFC
    // 9562 special cases, and v1 is a legitimate version. The ONLY shape it
    // refuses here is a version-0 value that is not nil — which is exactly and
    // solely `00000000-…-0001`. One digit away from an id Zod accepts.
    for (const id of [
      '00000000-0000-0000-0000-000000000000',   // nil — blessed by RFC 9562
      'ffffffff-ffff-ffff-ffff-ffffffffffff',   // max — likewise
      'e58ec6a0-5b0e-11ef-9454-0242ac120002',   // v1 — a real version
    ]) {
      expect(UUID.safeParse(id).success, id).toBe(true);
    }
  });

  it('accepts upper case, which Postgres normalises rather than refuses', () => {
    expect(UUID.safeParse('EC278D98-8726-4EE2-AD32-2DB940C9C0FE').success).toBe(true);
  });
});

describe('UUID — still rejects what is genuinely not an id', () => {
  it('rejects malformed strings', () => {
    // Relaxing the RFC check must not turn this into "any string". Each of
    // these would raise 22P02 at the database if it got through.
    for (const bad of [
      'not-a-uuid',
      '',
      '00000000-0000-0000-0000-00000000001',   // one digit short
      '00000000-0000-0000-0000-0000000000012', // one digit long
      '00000000-0000-0000-0000',               // truncated
      '00000000000000000000000000000001',      // no dashes
      'zzzzzzzz-zzzz-zzzz-zzzz-zzzzzzzzzzzz',  // non-hex
      '00000000-0000-0000-0000-000000000001 ', // trailing space
    ]) {
      expect(UUID.safeParse(bad).success, JSON.stringify(bad)).toBe(false);
    }
  });

  it('rejects non-strings', () => {
    for (const bad of [null, undefined, 42, {}, []]) {
      expect(UUID.safeParse(bad).success, String(bad)).toBe(false);
    }
  });
});
