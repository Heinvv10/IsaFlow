/**
 * The filing file of the live return version (wave 6 EFa): download it (VAT201 CSV or JSON, EMP201 CSV or PDF), see
 * who generated it and its sha256. The first download stamps the version, and Mark filed is offered only after that.
 * Owner/admin only, as filing is (the server refuses everyone else and Login-as). IsaFlow sends nothing to SARS.
 */
import { useState } from 'react';
import { Download } from 'lucide-react';
import { Button } from '@/components/ui/Button';
import { apiFetch } from '@/lib/apiFetch';
import { formatDate } from '@/utils/formatters';
import type { ReturnForm, ReturnVersionView } from './returnLifecycleClient';

const FORMATS: Record<ReturnForm, Array<['csv' | 'json' | 'pdf' | 'irp5', string]>> = {
  VAT201: [['csv', 'CSV'], ['json', 'JSON']],
  EMP201: [['csv', 'CSV'], ['pdf', 'PDF']],
  EMP501: [['irp5', 'e@syFile']], // wave 6 EFb
};
/** EMP501 has its own payroll-detail route (its file carries ID and tax numbers; wave 6 EFb). */
const urlOf = (form: ReturnForm): string => (form === 'EMP501'
  ? '/api/payroll/emp501/returns/filing-file' : `/api/accounting/sars/returns/${form.toLowerCase()}/filing-file`);

interface Props { form: ReturnForm; version: ReturnVersionView; nameOf: (id: string) => string; onStamped: () => void }

export function FilingFileActions({ form, version, nameOf, onStamped }: Props) {
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState('');
  const stamped = version.filingFileSha256 !== null;

  const download = async (format: 'csv' | 'json' | 'pdf' | 'irp5') => {
    setBusy(true); setError('');
    try {
      const res = await apiFetch(urlOf(form), {
        method: 'POST', headers: { 'Content-Type': 'application/json' }, credentials: 'include',
        body: JSON.stringify({ versionId: version.id, format }),
      });
      if (!res.ok) {
        const body = await res.json().catch(() => null) as { error?: { message?: string } } | null;
        setError(body?.error?.message ?? 'The filing file could not be generated. Reload the page and try again.');
        return;
      }
      const name = /filename="([^"]+)"/.exec(res.headers.get('Content-Disposition') ?? '')?.[1] ?? `${form}.${format}`;
      const url = URL.createObjectURL(await res.blob());
      const a = document.createElement('a');
      a.href = url; a.download = name;
      document.body.appendChild(a); a.click(); a.remove();
      URL.revokeObjectURL(url);
      if (!stamped) onStamped();
    } finally {
      setBusy(false);
    }
  };

  return (
    <div className="space-y-2" data-testid="filing-file">
      <p className="text-xs text-[var(--ff-text-secondary)]" data-testid="filing-file-status">
        {stamped
          ? <>Filing file generated by {nameOf(version.filingFileBy ?? '')} on {formatDate(version.filingFileAt ?? '')}
            {' '}(sha256 <span className="break-all">{version.filingFileSha256}</span>).</>
          : version.status === 'finalised'
            ? 'Download the filing file, capture it on SARS eFiling, then mark the return filed with the payment reference number eFiling shows.'
            : 'This version was filed before IsaFlow generated filing files.'}
      </p>
      <div className="flex flex-wrap gap-2">
        {FORMATS[form].map(([format, label]) => (
          <Button key={format} size="sm" variant="secondary" leftIcon={Download} disabled={busy} onClick={() => void download(format)}>
            Filing file ({label})
          </Button>
        ))}
      </div>
      {error && <p role="alert" className="text-sm text-red-500 dark:text-red-400">{error}</p>}
    </div>
  );
}
