/** Is `codePoint` one that Chromium breaks between when it meets another? Binary search over the ranges. */
export function breaksBetween(codePoint: number): boolean {
  let lo = 0;
  let hi = SELF_BREAKING.length - 1;
  while (lo <= hi) {
    const mid = (lo + hi) >> 1;
    const [from, to] = SELF_BREAKING[mid]!;
    if (codePoint < from) hi = mid - 1;
    else if (codePoint > to) lo = mid + 1;
    else return true;
  }
  return false;
}
