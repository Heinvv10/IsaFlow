/**
 * Apply a change of financial year end, in the request transaction.
 *
 * Mechanics (the brief left them to the implementer; chosen so that no journal,
 * balance or close run ever needs re-pointing):
 *
 *   1. The current year's row keeps its id, start and LABEL and gets the new end
 *      (kind 'transition'). Keeping the label means none of its periods is
 *      relabelled, so a month already closed inside it is untouched, and
 *      everything keyed by its label (budgets, AFS documents, close runs) stays
 *      put. Statements print the dates ("14 months ended 28 February 2027").
 *   2. The open years after it are deleted and rebuilt from the new template
 *      (twelve months on from the new end; labels follow the end-year rule and
 *      never repeat, fiscal_year_template in migration 940).
 *   3. Every period after the boundary keeps its row and id (so its journals,
 *      balance-cache rows and close runs are unaffected) and is re-pointed to
 *      the year that now holds its dates, relabelled by position. They are all
 *      open: the assessment refuses otherwise, and the database refuses to move
 *      a closed or locked period anyway.
 *   4. Missing months of the transition year and the whole next year are
 *      generated by the one generator, so the next year is visible at once.
 *   5. companies.financial_year_start becomes the month after the new end, a
 *      change record keeps a snapshot for undo, and the audit log records it.
 *
 * The invariants are re-checked by the database at COMMIT (periods inside
 * their year, the period-to-year FK) and here (every journal's period holds
 * its date), so a mistake rolls the whole change back.
 */

import { als } from '@/lib/als';
import { sql } from '@/lib/neon';
import type { DbRow } from '@/lib/neon';
import { log } from '@/lib/logger';
import { logAuditOrThrow } from '../core/auditTrailService';
import { assessYearEndChange, todayLocal, type YearEndChangeRequest } from './financialYearEndChangeService';
import { generateFiscalYearForDate } from './fiscalYearGenerator';
import { rehomePrimaryBudgetMonths } from '../budgets/budgetYearRehome';

export interface YearEndChangeApplyInput extends YearEndChangeRequest {
  reason: string;
  cipcFiledConfirmed: boolean;
  sarsNotifiedConfirmed: boolean;
  /**
   * The transition year's new end the user saw in the preview and confirmed
   * CIPC/SARS for. The route requires it; when given, apply refuses a different
   * outcome (a wizard left open across a year end would otherwise change the
   * NEXT year).
   */
  expectedEndDate?: string;
}

export class YearEndChangeRefusedError extends Error {
  constructor(readonly refusals: string[]) {
    super(refusals.join(' '));
    this.name = 'YearEndChangeRefusedError';
  }
}

export interface YearEndChangeResult {
  changeId: string;
  fiscalYearId: string;
  fiscalYear: number;
  startDate: string;
  endDate: string;
  months: number;
  movedPeriods: number;
  nextYearStart: string;
}

export function applyInputRefusals(input: YearEndChangeApplyInput): string[] {
  const out: string[] = [];
  if (typeof input.reason !== 'string' || input.reason.trim().length < 10) {
    out.push('Give the reason for the change (at least 10 characters).');
  } else if (input.reason.trim().length > 2000) {
    out.push('Keep the reason to 2000 characters.');
  }
  if (input.cipcFiledConfirmed !== true) out.push('Confirm that the notice of change has been filed with CIPC.');
  if (input.sarsNotifiedConfirmed !== true) out.push('Confirm that SARS has been notified of the change.');
  return out;
}

/**
 * Re-point an (open) period to the year that holds its dates, creating that year
 * from the template if needed, and number it by its position in the year. Two
 * statements on purpose: a year fiscal_year_ensure inserts is not visible to
 * the scan of the statement that called it.
 */
export async function repointPeriodToItsYear(companyId: string, periodId: string, startDate: string): Promise<void> {
  const ensured = (await sql`SELECT public.fiscal_year_ensure(${companyId}::UUID, ${startDate}::DATE) AS id`) as DbRow[];
  const yearId = String(ensured[0]!.id);
  await sql`
    UPDATE fiscal_periods fp
       SET fiscal_year_id = fy.id, fiscal_year = fy.fiscal_year,
           period_number = (EXTRACT(YEAR FROM fp.start_date)::int * 12 + EXTRACT(MONTH FROM fp.start_date)::int)
                         - (EXTRACT(YEAR FROM fy.start_date)::int * 12 + EXTRACT(MONTH FROM fy.start_date)::int) + 1
      FROM fiscal_years fy
     WHERE fy.id = ${yearId}::UUID AND fp.id = ${periodId}::UUID AND fp.company_id = ${companyId}::UUID
  `;
}

export async function applyYearEndChange(
  companyId: string, userId: string, input: YearEndChangeApplyInput, today: string = todayLocal(),
): Promise<YearEndChangeResult> {
  if (!als.getStore()?.client) throw new Error('applyYearEndChange must run inside the request transaction');
  const inputRefusals = applyInputRefusals(input);
  if (inputRefusals.length > 0) throw new YearEndChangeRefusedError(inputRefusals);

  // One change at a time per company; the assessment is re-read under the lock,
  // and every period from the current year on is row-locked first, so a period
  // closed concurrently is either seen by the assessment (a 409) or waits.
  await sql`SELECT pg_advisory_xact_lock(hashtextextended(${`fy-end-change:${companyId}`}, 0))`;
  await sql`
    SELECT fp.id FROM fiscal_periods fp
     WHERE fp.company_id = ${companyId}::UUID
       AND fp.end_date >= (SELECT MIN(fy.start_date) FROM fiscal_years fy
                            WHERE fy.company_id = ${companyId}::UUID AND fy.end_date >= ${today}::DATE)
     ORDER BY fp.id FOR UPDATE
  `;
  const a = await assessYearEndChange(companyId, input, today);
  if (a.refusals.length > 0 || !a.chosen) throw new YearEndChangeRefusedError(a.refusals);
  if (input.expectedEndDate !== undefined && a.chosen.endDate !== input.expectedEndDate) {
    throw new YearEndChangeRefusedError([`The change would now end FY${a.currentYear.fiscalYear} on ${a.chosen.endDate}, `
      + `not the ${input.expectedEndDate} you confirmed; preview it again.`]);
  }
  const year = a.currentYear;
  const chosen = a.chosen;

  // The current year must be a stored row to become the transition year.
  const yearId = year.id ?? (await generateFiscalYearForDate(companyId, year.startDate)).fiscalYearId;

  const boundary = chosen.endDate < year.endDate ? chosen.endDate : year.endDate;
  const changeRows = (await sql`
    INSERT INTO fiscal_year_end_changes (
      company_id, fiscal_year_id, from_start_month, to_start_month, transition_start, from_end_date, to_end_date,
      months, reason, cipc_filed_confirmed, sars_notified_confirmed, applied_by
    ) VALUES (
      ${companyId}::UUID, ${yearId}::UUID, ${a.currentStartMonth}, ${chosen.newStartMonth}, ${year.startDate}::DATE,
      ${year.endDate}::DATE, ${chosen.endDate}::DATE, ${chosen.months}, ${input.reason.trim()},
      true, true, ${userId}::UUID
    ) RETURNING id
  `) as DbRow[];
  const changeId = String(changeRows[0]!.id);

  await sql`SET CONSTRAINTS fiscal_periods_fiscal_year_id_fkey DEFERRED`;
  await sql`DELETE FROM fiscal_years WHERE company_id = ${companyId}::UUID AND start_date > ${year.startDate}::DATE`;
  await sql`
    UPDATE fiscal_years SET end_date = ${chosen.endDate}::DATE, kind = 'transition', change_id = ${changeId}::UUID
     WHERE id = ${yearId}::UUID AND company_id = ${companyId}::UUID
  `;

  // The new start month BEFORE any later year is built: the template chains on
  // from the transition year only when the year after it starts in the declared month.
  await sql`UPDATE companies SET financial_year_start = ${chosen.newStartMonth} WHERE id = ${companyId}::UUID`;

  // Free the (label, number) keys first: a moved period may take a key an
  // unmoved one still holds until its own turn.
  const moved = (await sql`
    UPDATE fiscal_periods SET period_number = -period_number - 1000
     WHERE company_id = ${companyId}::UUID AND start_date > ${boundary}::DATE
    RETURNING id, start_date::text AS start_date
  `) as DbRow[];
  moved.sort((x, y) => String(x.start_date).localeCompare(String(y.start_date)));
  for (const p of moved) {
    await repointPeriodToItsYear(companyId, String(p.id), String(p.start_date));
  }

  await sql`SELECT public.fiscal_periods_generate(${yearId}::UUID, true)`;
  await generateFiscalYearForDate(companyId, chosen.nextYearStart);
  await sql`SET CONSTRAINTS fiscal_periods_fiscal_year_id_fkey IMMEDIATE`;
  // Budget versions are keyed by year: the primary budget's months follow the months (decision 12).
  await rehomePrimaryBudgetMonths(companyId, boundary, userId);

  const drift = (await sql`
    SELECT COUNT(*)::int AS n FROM gl_journal_entries je JOIN fiscal_periods fp ON fp.id = je.fiscal_period_id
     WHERE je.company_id = ${companyId}::UUID AND fp.company_id = ${companyId}::UUID
       AND fp.start_date > ${boundary}::DATE AND je.entry_date NOT BETWEEN fp.start_date AND fp.end_date
  `) as DbRow[];
  if (Number(drift[0]!.n) > 0) {
    throw new Error(`Change of year end aborted: ${drift[0]!.n} journal(s) would sit in a period that does not hold their date`);
  }

  await logAuditOrThrow({
    companyId, userId, action: 'update', entityType: 'fiscal_year_end_change', entityId: changeId,
    entityRef: `FY${year.fiscalYear} ${year.startDate}..${chosen.endDate}`,
    changes: {
      fields: [
        { field: 'year_end', label: 'Financial year end', old: year.endDate, new: chosen.endDate },
        { field: 'financial_year_start', label: 'Financial year start month',
          old: String(a.currentStartMonth), new: String(chosen.newStartMonth) },
      ],
      metadata: {
        reason: input.reason.trim(), months: String(chosen.months), transitionStart: year.startDate,
        cipcFiledConfirmed: 'true', sarsNotifiedConfirmed: 'true', movedPeriods: String(moved.length),
      },
    },
  });
  log.info('Financial year end changed', { companyId, changeId, fiscalYear: year.fiscalYear, to: chosen.endDate }, 'accounting');

  return {
    changeId, fiscalYearId: yearId, fiscalYear: year.fiscalYear, startDate: year.startDate,
    endDate: chosen.endDate, months: chosen.months, movedPeriods: moved.length, nextYearStart: chosen.nextYearStart,
  };
}
