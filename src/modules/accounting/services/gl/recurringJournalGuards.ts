/**
 * The guards a recurring-journal run must clear BEFORE its first write.
 *
 * Its own file because `postJournalEntry` raises every one of these AFTER
 * `createJournalEntry` has INSERTed the draft — one write too late. `withAuth`
 * ROLLBACKs only on >= 500, so a refusal answered as 400 used to commit the
 * journal it said had not happened. Answering from a read here makes each one a
 * refusal with a remedy in it and nothing written.
 */

import { sql, withSavepoint } from '@/lib/neon';
import { als, assertTxUsable } from '@/lib/als';
import { validateJournalEntry } from '../../utils/doubleEntry';
import { ensureFiscalPeriodForDate } from './fiscalPeriodAutoCreate';
import { getPeriodStatusForDate } from './periodStatusService';
import type { JournalLineInput } from '../../types/gl.types';
import type { DbRow } from '@/types/db';

/**
 * A caller fault on a recurring-journal action — the template is missing, not
 * active, not due yet, or cannot be posted as it stands. The route answers
 * these with a 400; anything NOT of this class is a genuine failure that must
 * reach `withErrorHandler` as a 500 so `withAuth` ROLLBACKs the request.
 */
export class RecurringJournalRequestError extends Error {
  readonly code: string = 'RECURRING_JOURNAL_REQUEST';
  constructor(message: string) {
    super(message);
    this.name = 'RecurringJournalRequestError';
  }
}

/**
 * Contention, not a fault in the request: the same call will succeed once the
 * peer finishes. Its own class because every other member of the parent is
 * permanent until the operator changes something, and a client that cannot
 * tell "retry this" from "stop" will do the wrong one.
 */
export class RecurringJournalLockTimeoutError extends RecurringJournalRequestError {
  override readonly code = 'RECURRING_JOURNAL_LOCK_TIMEOUT';
  constructor(id: string) {
    super(`Recurring journal ${id} is being generated by another request — retry in a moment.`);
    this.name = 'RecurringJournalLockTimeoutError';
  }
}

/**
 * No template with this id in THIS company. Its own class so the route can
 * answer 404: a wrong id — including another tenant's, which is the shape the
 * cross-tenant test exercises — is not a malformed request, and a caller that
 * cannot tell the two apart retries the one it should abandon. Kept inside
 * `RecurringJournalRequestError` so every existing `instanceof` check, and the
 * "caller fault, do not roll back" contract, still hold.
 */
export class RecurringJournalNotFoundError extends RecurringJournalRequestError {
  override readonly code = 'RECURRING_JOURNAL_NOT_FOUND';
  constructor(readonly id: string) {
    super(`Recurring journal ${id} not found`);
    this.name = 'RecurringJournalNotFoundError';
  }
}

/** Postgres `lock_not_available` — the 5s `lock_timeout` elapsed on the template row. */
const LOCK_NOT_AVAILABLE = '55P03';

/**
 * Read the template and hold a row lock on it until the request transaction
 * ends. `generateJournalFromRecurring` refuses to run outside one, so the lock
 * really is held rather than released the instant the SELECT returns.
 *
 * Two details that are easy to get wrong:
 *
 * - The read runs in its OWN savepoint. When `lock_timeout` elapses Postgres
 *   aborts the whole transaction, so catching 55P03 and carrying on would leave
 *   an aborted transaction that answers the next statement with a bare 25P02.
 *   The savepoint rolls that back so the caller's refusal path is usable.
 * - `SET LOCAL lock_timeout` is scoped to the TRANSACTION, not to the statement,
 *   so leaving it set would cap `postJournalEntry`'s own row locks at 5s too.
 *   It is restored to DEFAULT once the read is done. It is also re-issued on
 *   every call rather than memoised: `SET LOCAL` is subtransaction-aware and a
 *   `ROLLBACK TO SAVEPOINT` restores it to 0 — no timeout at all.
 */
export async function readTemplateForUpdate(companyId: string, id: string): Promise<DbRow | undefined> {
  const client = als.getStore()?.client;
  if (!client) {
    throw new Error(
      'readTemplateForUpdate requires the request transaction on the ALS client (withAuth). '
      + 'Outside one, FOR UPDATE is released immediately and locks nothing.',
    );
  }
  assertTxUsable();
  try {
    const row = await withSavepoint('recurring_journal_lock', async () => {
      await client.query("SET LOCAL lock_timeout = '5s'");
      const rows = (await sql`
        SELECT * FROM recurring_journals
        WHERE id = ${id} AND company_id = ${companyId}
        FOR UPDATE
      `) as DbRow[];
      return rows[0];
    });
    // Success path only. RELEASE SAVEPOINT keeps the setting, so leaving it
    // would cap every later lock in this request at 5s; ROLLBACK TO SAVEPOINT
    // already restored it on the failure path below.
    await client.query('SET LOCAL lock_timeout = DEFAULT');
    return row;
  } catch (err) {
    if (typeof err === 'object' && err !== null && (err as { code?: unknown }).code === LOCK_NOT_AVAILABLE) {
      throw new RecurringJournalLockTimeoutError(id);
    }
    throw err;
  }
}

/**
 * Today in SAST, not `CURRENT_DATE`. The database session runs in UTC, so
 * between 00:00 and 02:00 SAST `CURRENT_DATE` is still yesterday and a template
 * dated for today would be refused as "not due until <today>" — a message that
 * contradicts the operator's calendar.
 */
export async function businessToday(): Promise<string> {
  const rows = (await sql`
    SELECT (NOW() AT TIME ZONE 'Africa/Johannesburg')::DATE::TEXT AS today
  `) as DbRow[];
  return String(rows[0]!.today);
}

/** A `gl_accounts.id` as Postgres will accept it; anything else is a 22P02, not a 400. */
const UUID_RE = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;

/**
 * Refuse a template whose stored lines cannot be posted as they stand.
 *
 * `postJournalEntry` raises both of these — `InactiveAccountError` and the
 * balance check — after the draft is written. A template's lines are a JSONB
 * snapshot taken when it was created, so an account deactivated since then is
 * the normal way a working template goes bad, and the operator needs the
 * account code, not "an unexpected error occurred".
 */
export async function assertTemplateLinesPostable(
  companyId: string,
  lines: JournalLineInput[],
): Promise<void> {
  if (lines.length === 0) {
    throw new RecurringJournalRequestError('This recurring journal template has no lines to post.');
  }

  const validation = validateJournalEntry(lines.map((l) => ({
    glAccountId: l.glAccountId, debit: l.debit, credit: l.credit,
  })));
  if (!validation.valid) {
    throw new RecurringJournalRequestError(
      `This recurring journal template does not balance: ${validation.errors.join('; ')}. `
      + 'Correct the template before generating from it.',
    );
  }

  const accountIds = [...new Set(lines.map((l) => l.glAccountId))];

  // Shape-check before the cast. `lines` is a JSONB snapshot and nothing on the
  // create or update path validates `glAccountId`, so a non-UUID reaches
  // `ANY(...::UUID[])` and Postgres raises 22P02 — not a
  // RecurringJournalRequestError, so the route rethrows and the operator gets
  // the same "an unexpected error occurred" 500 this guard exists to replace.
  const malformed = accountIds.filter((id) => typeof id !== 'string' || !UUID_RE.test(id));
  if (malformed.length > 0) {
    throw new RecurringJournalRequestError(
      `This recurring journal template has ${malformed.length} malformed GL account `
      + `reference${malformed.length === 1 ? '' : 's'}: ${malformed.map((id) => JSON.stringify(id)).sort().join(', ')}. `
      + 'Recode the template before generating from it.',
    );
  }

  const rows = (await sql`
    SELECT id, account_code, account_name, is_active
    FROM gl_accounts
    WHERE company_id = ${companyId}::UUID AND id = ANY(${accountIds}::UUID[])
  `) as DbRow[];

  const found = new Map(rows.map((r) => [String(r.id), r]));
  const missing = accountIds.filter((id) => !found.has(id));
  if (missing.length > 0) {
    throw new RecurringJournalRequestError(
      `This recurring journal template references ${missing.length} GL account`
      + `${missing.length === 1 ? '' : 's'} that no longer exist in this company. `
      + 'Recode the template before generating from it.',
    );
  }

  const inactive = rows.filter((r) => r.is_active === false)
    .map((r) => `${String(r.account_code)} ${String(r.account_name)}`);
  if (inactive.length > 0) {
    throw new RecurringJournalRequestError(
      `This recurring journal template posts to deactivated GL account`
      + `${inactive.length === 1 ? '' : 's'}: ${inactive.sort().join(', ')}. `
      + 'Reactivate the account, or recode the template.',
    );
  }
}

/**
 * Refuse a run whose fiscal period cannot take a posting — after creating the
 * year on demand, the way the posting path already does.
 *
 * A plain `getPeriodStatusForDate` here would REVERSE the repo's own policy.
 * `createJournalEntry` calls `ensureFiscalPeriodForDate`, which creates the
 * fiscal year within the auto-create window precisely because nothing creates
 * periods when a company is provisioned: a brand-new tenant has ZERO rows, so
 * every date falls outside every period. Refusing `no_period` from a read alone
 * turned a template that posted yesterday into a dead Generate button for any
 * company whose year nobody had created by hand.
 *
 * So the refusal is kept only for the case where creation would NOT have
 * happened: a year outside the window, where the entry would post with a NULL
 * `fiscal_period_id` — invisible to the trial balance, the VAT201 and the AFS,
 * which is the hazard the guard exists for.
 *
 * The creation is a write on a path that can still refuse afterwards, so it is
 * worth saying exactly when it can leave rows behind: never, on any refusal
 * that exists. `ensureFiscalPeriodForDate` returns early when a covering period
 * already exists, and the lookup it uses (`getFiscalPeriodIdForDate`) does NOT
 * filter on status — so a CLOSED period is found and nothing is written before
 * that refusal. The `no_period` refusal fires only for a year outside the
 * auto-create window, where creation was declined and nothing was written
 * either. The one theoretical exception is a `createFiscalYear` that succeeds
 * and still leaves the date uncovered; that is an inconsistency in the calendar
 * itself, not a path this guard takes. `createJournalEntry` would have created
 * the same periods a moment later anyway.
 */
export async function assertPostablePeriod(companyId: string, dueDate: string): Promise<void> {
  await ensureFiscalPeriodForDate(companyId, dueDate);

  const period = await getPeriodStatusForDate(companyId, dueDate);
  if (period === 'no_period') {
    throw new RecurringJournalRequestError(
      `No fiscal period covers ${dueDate}, the date this run is scheduled for, and that year is `
      + 'too far from today to be created automatically. Create the fiscal year first — posting '
      + 'outside every period would leave the journal invisible to the trial balance, the VAT201 '
      + 'and the AFS.',
    );
  }
  if (period !== 'open') {
    throw new RecurringJournalRequestError(
      `The fiscal period covering ${dueDate}, the date this run is scheduled for, is ${period}. `
      + 'Re-open it before generating into it.',
    );
  }
}
